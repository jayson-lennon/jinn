//! Build script: generates the embedded vendor-asset table from the
//! canvas vendor manifest, verifying every manifest row against the
//! actual bytes on disk before any code compiles against them.
//!
//! The `/vendor/` inventory the apps server serves must be byte-identical
//! to canvas's, but `jinn-apps` must never depend on the canvas
//! implementation crate. The resolution is a build-time file path, not a
//! crate edge: this script reads the same `vendor-manifest.toml` and the
//! same files under `jinn-canvas/resources/vendor/` — the
//! manifest-defined inventory the contract names — runs the identical
//! sha256 pin gate canvas's build runs, and emits the same row shape
//! into this crate's `OUT_DIR`. A manifest row or a file that disagrees
//! fails this build the same way it fails canvas's, so the two tables can
//! never drift apart silently.
//!
//! The two authored canvas files (`canvas.css`, `canvas-telemetry.js`)
//! are included: parity means the whole inventory, and a saved app that
//! references either serves the same bytes it would have gotten from a
//! live canvas server.

// A build script's panic is its failure channel: every pin violation must
// fail the build loudly, not quietly produce a binary serving unverified
// bytes. expect/unwrap carry the same contract.
#![allow(clippy::panic, reason = "build script: panic is the failure channel")]
#![allow(
    clippy::expect_used,
    reason = "build script: env and IO failures are fatal by contract"
)]

use marked_path::MarkedPathAccess as _;
use sha2::Digest as _;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// The workspace-relative location of the shared vendor tree, resolved
/// against this crate's manifest dir: `../../jinn-canvas/resources/vendor`.
fn vendor_dir(manifest_dir: &Path) -> marked_path::MarkedPathBuf<marked_path::Absolute> {
    match marked_path::MarkedPathBuf::<marked_path::Absolute>::new(
        manifest_dir
            .join("..")
            .join("jinn-canvas")
            .join("resources")
            .join("vendor"),
    ) {
        Ok(dir) => dir,
        Err(error) => panic!("vendor dir did not type-check: {error}"),
    }
}

fn main() {
    #[expect(
        clippy::disallowed_types,
        reason = "build-script env plumbing (CARGO_MANIFEST_DIR) predates typed-path flow; consumed only to derive the typed vendor dir"
    )]
    let manifest_dir =
        std::path::PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let vendor_dir = vendor_dir(&manifest_dir);
    // `join` refuses to leave the absolute base — a typed-path no-op that
    // also proves the manifest name carries no traversal.
    let manifest_path = vendor_dir
        .join("vendor-manifest.toml")
        .expect("a bare file name joins");

    println!(
        "cargo:rerun-if-changed={}",
        manifest_path.as_path().display()
    );
    println!("cargo:rerun-if-changed={}", vendor_dir.as_path().display());

    let manifest_text = fs::read_to_string(manifest_path.as_path())
        .unwrap_or_else(|e| panic!("reading {}: {e}", manifest_path.as_path().display()));
    let manifest: toml::Value =
        toml::from_str(&manifest_text).expect("vendor-manifest.toml must parse as TOML");

    let assets = manifest
        .get("assets")
        .and_then(toml::Value::as_array)
        .expect("vendor-manifest.toml must carry an [[assets]] array");

    let mut table = String::from(
        "// @generated by jinn-apps/build.rs from jinn-canvas's vendor manifest — do not edit.\n\
         // Byte-identical to jinn-canvas's generated table by construction: same manifest\n\
         // rows, same files, same sha256 gate.\n\
         \n\n\
         /// The complete vendor inventory. `path` is the `/vendor/`-relative served\n\
         /// path; `bytes` is exactly the file content (gzipped for library dists,\n\
         /// plain for licenses, fonts, and authored files); `encoding` says whether\n\
         /// the server marks the response `Content-Encoding: gzip` or identity.\n\
         #[derive(Clone, Copy)]\n\
         pub struct VendorAsset {\n    \
             pub path: &'static str,\n    \
             pub bytes: &'static [u8],\n    \
             pub encoding: &'static str,\n    \
             pub content_type: &'static str,\n\
         }\n\n\
         pub const VENDOR_ASSETS: &[VendorAsset] = &[\n",
    );

    let mut seen: Vec<String> = Vec::new();
    for asset in assets {
        let served = str_field(asset, "served");
        let sha = str_field(asset, "sha256");

        // Served paths are emitted verbatim into the generated
        // `include_bytes!` literal, so a backslash here would become an
        // invalid escape sequence on the Windows side of the build.
        assert!(
            !served.contains('\\'),
            "vendor manifest served paths must use forward slashes: {served}"
        );

        // Reject duplicates so one served path can never shadow another.
        assert!(
            !seen.iter().any(|s| s == served),
            "vendor manifest names {served} twice"
        );
        seen.push(served.to_owned());

        // `encoding` is optional and defaults to identity: the gzipped
        // library dists always state it, everything else needs not.
        let encoding = asset
            .get("encoding")
            .and_then(toml::Value::as_str)
            .unwrap_or("identity");

        let file_path = vendor_dir.join_all([served]).unwrap_or_else(|error| {
            panic!("vendor asset path {served} did not type-check: {error}")
        });
        let bytes = fs::read(file_path.as_path()).unwrap_or_else(|e| {
            panic!(
                "vendor asset {} missing from disk ({e}) — run `just canvas-vendor-update`",
                file_path.as_path().display()
            )
        });
        verify_sha(served, &bytes, sha);

        let content_type = content_type_for(served);

        let open_row = if bytes.len() > 1_000_000 {
            "#[expect(clippy::large_include_file, reason = \"committed gzip exceeds the 1 MB include guard by design; raw is never committed\")]\n    { VendorAsset"
        } else {
            "    VendorAsset"
        };
        let close_row = if bytes.len() > 1_000_000 { " }," } else { "," };

        // The file path is emitted as a `concat!` against the *canvas*
        // crate's manifest dir, computed here once and pasted verbatim
        // with forward slashes only — the same machine-independent
        // emission rule canvas's build uses.
        let canvas_vendor_literal = canvas_vendor_literal(&manifest_dir);
        let _ = writeln!(
            table,
            "{open_row} {{\n        path: \"{served}\",\n        bytes: include_bytes!(concat!(\"{canvas_vendor_literal}\", \"/{served}\")),\n        encoding: \"{encoding}\",\n        content_type: \"{content_type}\",\n    }}{close_row}"
        );
    }

    // The two authored canvas files are jinn-owned, not manifest-pinned,
    // so they are absent from the manifest — canvas's build emits their
    // static rows after the manifest loop, and parity means apps emits
    // the same rows here. Each `fs::read` is the existence check; a
    // missing authored asset fails this build the same way it fails
    // canvas's.
    let canvas_vendor_literal = canvas_vendor_literal(&manifest_dir);
    for (served, content_type) in [
        ("canvas.css", "text/css; charset=utf-8"),
        ("canvas-telemetry.js", "text/javascript; charset=utf-8"),
    ] {
        let file_path = vendor_dir.join_all([served]).unwrap_or_else(|error| {
            panic!("authored vendor asset path {served} did not type-check: {error}")
        });
        fs::read(file_path.as_path()).unwrap_or_else(|e| {
            panic!(
                "authored vendor asset {} missing from disk ({e})",
                file_path.as_path().display()
            )
        });
        let _ = writeln!(
            table,
            "    VendorAsset {{\n        path: \"{served}\",\n        bytes: include_bytes!(concat!(\"{canvas_vendor_literal}\", \"/{served}\")),\n        encoding: \"identity\",\n        content_type: \"{content_type}\",\n    }},"
        );
    }

    let _ = writeln!(table, "];\n");

    #[expect(
        clippy::disallowed_types,
        reason = "OUT_DIR is cargo's own env plumbing, consumed only to write the generated vendor_assets.rs"
    )]
    let out_dir = std::path::PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("vendor_assets.rs"), table)
        .expect("writing vendor_assets.rs into OUT_DIR cannot fail");
}

/// The `concat!`-safe absolute prefix of the shared vendor tree:
/// `CARGO_MANIFEST_DIR`-relative from the canvas crate, forward-slashed.
///
/// Emitted as a literal into the generated `concat!`, never via
/// `Path::display` (which produces backslashes on Windows).
fn canvas_vendor_literal(manifest_dir: &Path) -> String {
    // Walk up from crates/slices/jinn-apps to the workspace root, then
    // down into the canvas crate's vendor dir.
    let workspace_root = manifest_dir
        .parent() // slices/
        .and_then(Path::parent) // crates/
        .and_then(Path::parent) // workspace root
        .expect("jinn-apps sits three levels below the workspace root");
    let path = workspace_root
        .join("crates")
        .join("slices")
        .join("jinn-canvas")
        .join("resources")
        .join("vendor");
    path.to_string_lossy()
        .replace(std::path::MAIN_SEPARATOR, "/")
}

/// Reads a required string field, failing with the asset path in the panic
/// so a bad row names the file that broke the build.
fn str_field<'a>(asset: &'a toml::Value, key: &str) -> &'a str {
    asset
        .get(key)
        .and_then(toml::Value::as_str)
        .unwrap_or_else(|| panic!("vendor asset row missing {key}: {asset}"))
}

/// Verifies one row's sha256 against the bytes read from disk.
fn verify_sha(served: &str, bytes: &[u8], expected: &str) {
    let digest = sha2::Sha256::digest(bytes);
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        let _ = write!(hex, "{byte:02x}");
    }
    assert!(
        hex == expected,
        "vendor asset {served} does not match its manifest pin (expected {expected}, got {hex})"
    );
}

/// MIME type by served extension — byte-identical dispatch to canvas's
/// build script, so identical bytes always ride identical headers.
fn content_type_for(path: &str) -> &'static str {
    let name = path.rsplit('/').next().unwrap_or(path);
    let ext = name.rsplit('.').next().unwrap_or(name);
    if ext == name {
        // No dot in the file name: an extensionless license notice.
        return "text/plain; charset=utf-8";
    }
    match ext {
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "woff2" => "font/woff2",
        // `.txt` and the license notices (`LICENSE`, `vega.LICENSE`)
        // share the plain-text type.
        "txt" | "LICENSE" => "text/plain; charset=utf-8",
        "html" => "text/html; charset=utf-8",
        _ => "application/octet-stream",
    }
}
