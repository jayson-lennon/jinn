//! Build script: generates the embedded vendor-asset table from the
//! manifest, verifying every manifest row against the actual bytes on
//! disk before any code compiles against them.
//!
//! The verification here is the pin gate — invariant 3. The build fails
//! if a manifest row's sha256 disagrees with the file it names, if a
//! manifest row names a file that does not exist, or if a file exists
//! without a manifest row (a stray drop-in cannot ride along unvouched).
//! The generated table is the single inventory the server serves from.

// A build script's panic is its failure channel: every pin violation must
// fail the build loudly, not quietly produce a binary serving unverified
// bytes. expect/unwrap carry the same contract.
#![allow(clippy::panic, reason = "build script: panic is the failure channel")]
#![allow(
    clippy::expect_used,
    reason = "build script: env and IO failures are fatal by contract"
)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use sha2::Digest as _;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let vendor_dir = manifest_dir.join("resources/vendor");
    let manifest_path = vendor_dir.join("vendor-manifest.toml");

    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-changed={}", vendor_dir.display());

    let manifest_text = fs::read_to_string(&manifest_path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", manifest_path.display()));
    let manifest: toml::Value =
        toml::from_str(&manifest_text).expect("vendor-manifest.toml must parse as TOML");

    let assets = manifest
        .get("assets")
        .and_then(toml::Value::as_array)
        .expect("vendor-manifest.toml must carry an [[assets]] array");

    let mut table = String::from(
        "// @generated by build.rs from resources/vendor/vendor-manifest.toml — do not edit.\n\
         // One row per vendored asset; `include_bytes!` is emitted relative to CARGO_MANIFEST_DIR.\n\
         \n\n\
         /// The complete vendor inventory. `path` is the `/vendor/`-relative served\n\
         /// path; `bytes` is exactly the file content (gzipped for library dists,\n\
         /// plain for licenses, fonts, and authored files); `encoding` says whether\n\
         /// the server marks the response `Content-Encoding: gzip` or identity.\n\
         #[derive(Clone, Copy)]\n\
         pub struct VendorAsset {\n    \
             pub path: &'static str,\n    \
             pub bytes: &'static [u8],\n    \
             pub encoding: &'static str,\n    \
             pub content_type: &'static str,\n\
         }\n\n\
         pub const VENDOR_ASSETS: &[VendorAsset] = &[\n",
    );

    let mut seen: Vec<String> = Vec::new();
    for asset in assets {
        let served = str_field(asset, "served");
        let sha = str_field(asset, "sha256");

        // Reject duplicates so one served path can never shadow another.
        assert!(
            !seen.iter().any(|s| s == served),
            "vendor manifest names {served} twice"
        );
        seen.push(served.to_owned());

        // `encoding` is optional and defaults to identity: the gzipped
        // library dists always state it, everything else needs not.
        let encoding = asset
            .get("encoding")
            .and_then(toml::Value::as_str)
            .unwrap_or("identity");

        let file_path = vendor_dir.join(served);
        let bytes = fs::read(&file_path).unwrap_or_else(|e| {
            panic!(
                "vendor asset {} missing from disk ({e}) — run `just canvas-vendor-update`",
                file_path.display()
            )
        });
        verify_sha(served, &bytes, sha);

        let content_type = content_type_for(served);

        // Mermaid's committed gzip is over clippy's include guard by
        // design; the row carries its own justified allowance.
        // Mermaid's committed gzip is over clippy's include guard by
        // design. Attributes on expressions are unstable, so an oversized
        // row is wrapped in an attributed block around the literal.
        let open_row = if bytes.len() > 1_000_000 {
            "#[expect(clippy::large_include_file, reason = \"committed gzip exceeds the 1 MB include guard by design; raw is never committed\")]\n    { VendorAsset"
        } else {
            "    VendorAsset"
        };
        let close_row = if bytes.len() > 1_000_000 { " }," } else { "," };
        let _ = writeln!(
            table,
            "{open_row} {{\n        path: \"{served}\",\n        bytes: include_bytes!(\"{}\"),\n        encoding: \"{encoding}\",\n        content_type: \"{content_type}\",\n    }}{close_row}",
            file_path.display()
        );
    }

    // Every file on disk must be vouched for by a manifest row: a stray
    // file dropped into the tree cannot ride into the binary unverified.
    // The authored canvas.css is the one exemption (its static row is
    // emitted below, outside the manifest pin).
    let mut unvouched: Vec<String> = Vec::new();
    collect_files(&vendor_dir, &vendor_dir, &mut unvouched);
    for path in &unvouched {
        assert!(
            path == "canvas.css" || seen.iter().any(|s| s == path),
            "vendor file {} has no manifest row",
            vendor_dir.join(path).display()
        );
    }

    // The authored canvas.css rides the same table; its row is static, not
    // generated from the manifest (jinn owns it, not an upstream pin). The
    // read is the existence check — a missing stylesheet fails the build.
    let css_path = vendor_dir.join("canvas.css");
    let _ = fs::read(&css_path).expect("resources/vendor/canvas.css is authored and must exist");
    let _ = writeln!(
        table,
        "    VendorAsset {{\n        path: \"canvas.css\",\n        bytes: include_bytes!(\"{}\"),\n        encoding: \"identity\",\n        content_type: \"text/css; charset=utf-8\",\n    }},",
        css_path.display()
    );
    let _ = writeln!(table, "];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("vendor_assets.rs"), table)
        .expect("writing vendor_assets.rs into OUT_DIR cannot fail");
}

/// Reads a required string field, failing with the asset path in the panic
/// so a bad row names the file that broke the build.
fn str_field<'a>(asset: &'a toml::Value, key: &str) -> &'a str {
    asset
        .get(key)
        .and_then(toml::Value::as_str)
        .unwrap_or_else(|| panic!("vendor asset row missing {key}: {asset}"))
}

/// Verifies one row's sha256 against the bytes read from disk.
fn verify_sha(served: &str, bytes: &[u8], expected: &str) {
    let digest = sha2::Sha256::digest(bytes);
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        let _ = write!(hex, "{byte:02x}");
    }
    assert!(
        hex == expected,
        "vendor asset {served} does not match its manifest pin (expected {expected}, got {hex})"
    );
}

/// Every regular file under `root`, as `root`-relative paths with forward
/// slashes — the shape `vendor_dir.join(served)` and the manifest both use.
fn collect_files(root: &Path, base: &Path, out: &mut Vec<String>) {
    let entries = fs::read_dir(root).unwrap_or_else(|e| panic!("reading {}: {e}", root.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("reading {}: {e}", root.display()));
        let path = entry.path();
        if path.is_dir() {
            collect_files(&path, base, out);
        } else {
            match path.file_name() {
                Some(name) if name != "vendor-manifest.toml" => {
                    let rel = path
                        .strip_prefix(base)
                        .expect("files collected under base are prefix-strippable")
                        .to_string_lossy()
                        .replace(std::path::MAIN_SEPARATOR, "/");
                    out.push(rel);
                }
                _ => {}
            }
        }
    }
}

/// MIME type by served extension. The set covers every extension the
/// vendor tree and the artifact surface can produce; text types carry
/// charset for correct rendering. Extensionless files (the license
/// notices) serve as plain text.
fn content_type_for(path: &str) -> &'static str {
    let name = path.rsplit('/').next().unwrap_or(path);
    let ext = name.rsplit('.').next().unwrap_or(name);
    if ext == name {
        // No dot in the file name: an extensionless license notice.
        return "text/plain; charset=utf-8";
    }
    match ext {
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "woff2" => "font/woff2",
        // `.txt` and the license notices (`LICENSE`, `vega.LICENSE`)
        // share the plain-text type.
        "txt" | "LICENSE" => "text/plain; charset=utf-8",
        "html" => "text/html; charset=utf-8",
        _ => "application/octet-stream",
    }
}
