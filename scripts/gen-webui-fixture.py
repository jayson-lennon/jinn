#!/usr/bin/env python3
"""Generates the webui client's contract fixture from the Rust source.

Reads `crates/slices/jinn-webui/src/contract.rs` (the DOM and path
constants) and `crates/slices/jinn-webui-msg/src/wire.rs` (the SSE
event names), and writes `webui/client/src/wire-fixture.ts` — the
fixture `wire.test.ts` checks the runtime values against.

This is the mechanization that replaced the hand-maintained FIXTURE:
the fixture cannot drift from the Rust contract because it is
*generated from* the Rust contract on every `just webui-build`. The
file carries a GENERATED header; hand edits to it are overwritten.

Usage: gen-webui-fixture.py <contract.rs> <wire.rs> <out.ts>
"""

import re
import sys


def fail(message: str) -> None:
    sys.exit(f"gen-webui-fixture: {message}")


def parse_constants(source: str, arrays: list[str]) -> list[str]:
    """Returns the values the named `pub const NAME: &[&str]` arrays
    resolve to. Each array entry is a constant IDENTIFIER (the Rust
    idiom), resolved against the file's standalone `pub const ID:
    &str = "value";` definitions — so a constant added to an array
    but never defined, or vice versa, fails loudly here."""
    defs = dict(
        (name, value)
        for name, value in re.findall(
            r'pub const (\w+): &str = "((?:[^"\\]|\\.)*)";', source
        )
    )
    values: list[str] = []
    for name in arrays:
        block = re.search(
            rf"pub const {name}: &\[&str\] = &\[(.*?)\];", source, re.DOTALL
        )
        if block is None:
            fail(f"no pub const {name}: &[&str] found in contract.rs")
        for identifier in re.findall(r"(\w+)", block.group(1)):
            if identifier in defs:
                values.append(defs[identifier])
            # Non-identifiers inside the array (whitespace, commas)
            # are skipped by the \w+ scan's misses below.
    if not values:
        fail("the arrays resolved to no values — parse failure?")
    return values


def parse_event_names(source: str) -> dict[str, str]:
    """Returns SseKind variant => event name, from the enum order and
    the event_name match arms."""
    variants = re.findall(r"^\s{4}(\w+),", source, re.MULTILINE)
    arms = dict(
        (variant, name)
        for variant, name in re.findall(
            r"Self::(\w+) => \"((?:[^\"\\]|\\.)*)\"", source
        )
    )
    if not variants:
        fail("no SseKind variants found in wire.rs")
    names: dict[str, str] = {}
    for variant in variants:
        if variant not in arms:
            fail(f"SseKind::{variant} has no event_name arm")
        names[variant.lower()] = arms[variant]
    return names


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(
            f"usage: {sys.argv[0]} <contract.rs> <wire.rs> <out.ts>"
        )
    contract_path, wire_path, out_path = sys.argv[1:4]

    contract_src = open(contract_path, encoding="utf-8").read()
    wire_src = open(wire_path, encoding="utf-8").read()

    dom_values = parse_constants(contract_src, ["DOM_CONSTANTS", "CLIENT_URLS"])
    if not dom_values:
        fail("the contract names no constants — parse failure?")
    # Dedupe: two constants may carry one value (VENDOR_APP_JS and
    # VENDOR_APP_JS_PATH both name main.js); the fixture is a *value*
    # set — the test checks coverage, not identity.
    dom_values = list(dict.fromkeys(dom_values))
    events = parse_event_names(wire_src)

    lines = [
        "//! GENERATED by `just webui-build` (scripts/gen-webui-fixture.py)",
        "//! from the Rust contract — DO NOT EDIT BY HAND.",
        "//!",
        "//! The fixture `wire.test.ts` checks `wire.ts`'s runtime values",
        "//! against. The Rust side greps `wire.ts`'s source directly",
        "//! (`contract_tests.rs`). Two directions, one generated truth.",
        "//! Test code: fixture comparison only.",
        "",
        "/** The Rust contract's DOM and path constants, name-mapped. */",
        "export const CONTRACT = {",
    ]
    for value in dom_values:
        key = value.upper().replace("-", "_").replace("/", "_")
        lines.append(f'  "{key}": "{value}",')
    lines += [
        "} as const;",
        "",
        "/** The Rust `SseKind::event_name()` values, keyed by variant. */",
        "export const SSE_KINDS = {",
    ]
    for variant, name in events.items():
        lines.append(f'  {variant}: "{name}",')
    lines += [
        "} as const;",
        "",
    ]
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    print(f"    wrote {out_path} ({len(dom_values)} constants, {len(events)} sse kinds)")


if __name__ == "__main__":
    main()
